TW.getLang = function () {
  return localStorage.getItem("tw_lang") || "en";
};

TW.setLang = function (lang) {
  localStorage.setItem("tw_lang", lang === "zh" ? "zh" : "en");
};

TW.t = function (key) {
  const lang = TW.getLang();
  return (TW.i18n[lang] && TW.i18n[lang][key]) || TW.i18n.en[key] || key;
};

TW.tt = function (item, field) {
  const lang = TW.getLang();
  if (!item) return "";
  if (lang === "zh" && item[field + "Zh"]) return item[field + "Zh"];
  return item[field] || "";
};
